    public static String lastMessage(String text) {
        String t = text.trim();
        if (t.isEmpty()) return "";
        String[] lines = t.split("\\r?\\n");
        for (int i = lines.length - 1; i >= 0; i--) {
            String line = lines[i].trim();
            if (!line.isEmpty()) return line.replaceFirst("^(对方|她|他|TA|朋友|女生|男生)[：:]", "").trim();
        }
        return t;
    }

    private static boolean has(String text, String... keys) {
        for (String s : keys) if (text.contains(s)) return true;
        return false;
    }

